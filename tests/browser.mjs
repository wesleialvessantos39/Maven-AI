import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fixture, root } from './helpers.mjs';
const f = await fixture();
const executable = process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE;
let browser;
try {
  browser = await chromium.launch({ ...(executable ? { executablePath: executable } : {}), headless: true, args: ['--no-sandbox'] });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(f.base);
  await page.getByRole('heading', { name: 'Visão geral', exact: true }).waitFor();
  await page.getByRole('combobox', { name: 'Projeto ativo', exact: true }).selectOption('sample');
  const nav = label => page.locator('.sidebar').getByRole('button', { name: label, exact: true }).click();
  await nav('Planejamento');
  await page.getByLabel('Objetivo do projeto ou alteração').fill('Criar sistema SaaS preservando funcionalidades existentes');
  await page.getByLabel('Tipo de sistema', { exact: true }).selectOption('saas');
  await page.getByRole('button', { name: 'Criar plano', exact: true }).click();
  await page.locator('.plan-overview').waitFor();
  const first = page.locator('.plan-task').first();
  await first.getByRole('combobox').selectOption('concluida');
  await first.getByRole('textbox').fill('Resultado observado: testes e build executados no ambiente de teste.');
  await first.getByRole('button', { name: 'Salvar etapa' }).click();
  await first.locator('.task-state').filter({ hasText: 'Concluída' }).waitFor();
  await page.getByRole('button', { name: 'Revisar plano com IA' }).click();
  await page.getByRole('heading', { name: 'Revisão consultiva da IA' }).waitFor();
  await nav('Segurança'); await page.getByRole('button', { name: 'Auditar projeto', exact: true }).click();
  await page.getByRole('heading', { name: 'Execução dinâmica de código' }).waitFor();
  await nav('Laboratório');
  for (const [label, value] of [['Título', 'Investigar comportamento da tela'], ['Hipótese testável', 'JSX sem runtime automático impede renderização'], ['Experimento reproduzível', 'Abrir o navegador e verificar console e conteúdo do root'], ['Resultado esperado', 'Interface renderizada sem erros JavaScript']]) await page.getByLabel(label, { exact: true }).fill(value);
  await page.getByRole('button', { name: 'Salvar investigação' }).click();
  await page.getByRole('heading', { name: 'Investigar comportamento da tela' }).waitFor();
  await nav('Assistente IA'); await page.getByLabel('Especialidade').selectOption('cientista');
  await page.getByLabel('Mensagem', { exact: true }).fill('Investigue a hipótese e sugira um experimento.');
  await page.getByRole('button', { name: 'Enviar', exact: true }).click();
  await page.locator('.message.assistant').waitFor();
  assert.match(await page.locator('.message.assistant').innerText(), /Resposta simulada/);
  await nav('Superpowers e Context7');
  const debugSkill=page.locator('.tool-skills article').filter({hasText:'systematic-debugging'});
  await debugSkill.getByRole('button',{name:'Ler habilidade'}).click();
  await page.getByLabel('Arquivo de referência Superpowers',{exact:true}).waitFor();
  await page.getByLabel('Objetivo da análise com Superpowers',{exact:true}).fill('Investigar o erro de tela vazia preservando o aplicativo');
  await page.getByRole('button',{name:'Analisar com esta habilidade'}).click();
  await page.getByRole('heading',{name:'Análises por metodologia'}).waitFor();
  await debugSkill.getByRole('checkbox').check();
  await page.getByRole('button',{name:'Salvar configuração do projeto'}).click();
  await page.getByRole('status').filter({hasText:'Configuração salva'}).waitFor();
  for (const name of ['Editor inteligente', 'Criar projeto', 'Supabase', 'GitHub e Vercel', 'Conhecimento', 'Desempenho', 'Visão geral']) { await nav(name); await page.getByRole('heading', { name, exact: true, level: 1 }).waitFor(); }
  await fs.mkdir(path.join(root, 'artifacts'), { recursive: true });
  await page.screenshot({ path: path.join(root, 'artifacts/desktop.png'), fullPage: true });
  await page.setViewportSize({ width: 375, height: 812 });
  await page.getByRole('button', { name: 'Abrir menu', exact: true }).click(); await nav('Planejamento');
  await page.getByRole('heading', { level: 1, name: 'Planejamento', exact: true }).waitFor();
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Sem rolagem horizontal no celular');
  await page.screenshot({ path: path.join(root, 'artifacts/mobile.png'), fullPage: true });
  await page.reload(); await page.getByRole('heading', { name: 'Visão geral', exact: true }).waitFor();
  assert.deepEqual(errors, []);
  console.log('PASSOU: abertura, navegação, plano/dependências, revisão com modelo simulado, auditoria, laboratório, chat, Superpowers/Context7, recarga e viewport 375px. Nenhum erro JavaScript.');
} finally { await browser?.close(); await f.cleanup(); }
